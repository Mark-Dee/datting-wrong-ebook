/**
 * Generates src/data/publicBook.generated.ts — the ONLY book data shipped to the browser.
 * It contains metadata, the table of contents, and the free-preview sections/pages.
 * Protected chapters never enter the client bundle; they are served by /api/book/pages
 * after the server verifies a Firebase ID token and an ACTIVE entitlement.
 *
 * Run: npm run generate:public-book   (also runs automatically before dev/build)
 */
import fs from 'node:fs';
import path from 'node:path';
import { MANUSCRIPT_V1 } from '../server/book/manuscript-v1.ts';
import { ALL_BOOK_PAGES } from '../server/book/manuscript/allPages.ts';
import { FREE_PREVIEW_SECTION_IDS } from '../server/book/access.ts';

const free = new Set<string>(FREE_PREVIEW_SECTION_IDS);

const sections = MANUSCRIPT_V1.sections.map((s) =>
  free.has(s.id)
    ? s
    : {
        id: s.id,
        order: s.order,
        type: s.type,
        numberLabel: s.numberLabel,
        title: s.title,
        subtitle: s.subtitle,
        paragraphs: [] as string[],
        readingMinutes: s.readingMinutes,
      }
);

const previewPages = ALL_BOOK_PAGES.filter(
  (p) => free.has(p.sectionId) || p.sectionId === 'title-page' || p.sectionId === 'contents'
);

const out = `/* AUTO-GENERATED by scripts/generatePublicBook.ts — do not edit; contains NO protected chapter text. */
import type { BookVersionData, BookPage } from '../types.ts';

export const PUBLIC_BOOK: BookVersionData = ${JSON.stringify({ metadata: MANUSCRIPT_V1.metadata, sections }, null, 2)};

export const PREVIEW_PAGES: BookPage[] = ${JSON.stringify(previewPages, null, 2)};
`;
fs.writeFileSync(path.resolve('src/data/publicBook.generated.ts'), out);
console.log(`[public-book] ${sections.length} sections (${free.size} free), ${previewPages.length} preview pages`);
